from logic.llm.gigachat_api import ask_gigachat


def generate_meal_plan(products: str, days: int, meals_per_day: int) -> str:
    """
    Формирует чёткий промт для генерации плана питания через GigaChat.
    """

    prompt = f"""
Ты — профессиональный диетолог и шеф-повар. 
Составь персональный план питания строго на {days} {'день' if days == 1 else 'дней'}.

❗️Условия:
1. Используй только продукты из списка пользователя.
2. Не добавляй никаких других ингредиентов.
3. Составь ровно {meals_per_day} приём(а) пищи в день.
4. Укажи рецепты для каждого блюда — коротко и пошагово.
5. Не добавляй комментарии, пояснения, советы или примечания.
6. Форматируй строго в следующем виде:

День 1:
- Завтрак: <название блюда>
  Рецепт: <инструкция>
- Обед: ...
- Ужин: ...

Если дни > 1, повтори структуру для каждого дня (День 2:, День 3:, ...).

📋 Список доступных продуктов:
{products}
"""

    return ask_gigachat(prompt)
