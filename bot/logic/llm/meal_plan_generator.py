from logic.llm.gigachat_api import ask_gigachat

def generate_meal_plan(products, days, meals_per_day):
    product_list = ", ".join(products)

    prompt = f"""
Ты — профессиональный диетолог и нутриционист. 
Составь подробный план питания на {days} дней с {meals_per_day} приёмами пищи в день.
Используй только следующие продукты: {product_list}.

Если продуктов недостаточно, предложи оптимальный план исходя из доступных ингредиентов, 
дополняя рацион простыми и здоровыми вариантами из базовых продуктов (например, овсянка, рис, яйца, овощи, фрукты).

Структурируй ответ так:
День 1:
- Завтрак: ...
- Обед: ...
- Ужин: ...
(и так далее для каждого дня)

Не используй сложные ингредиенты, придерживайся доступных и простых рецептов.
    """

    return ask_gigachat(prompt).strip()
