from logic.llm.gigachat_api import ask_gigachat


def generate_meal_plan(products: str, days: int, meals: int) -> str:
    prompt = f"""
Ты — профессиональный нутрициолог и шеф-повар.

Твоя задача — составить подробный, но краткий план питания строго из предоставленных продуктов.
Не добавляй ни один ингредиент, которого нет в списке. 
Если какого-то продукта не хватает для разнообразия, просто используй доступные варианты в других комбинациях. 
Не придумывай новые продукты.

Дано:
📦 Доступные продукты: {products}
📅 Количество дней: {days}
🍽️ Приёмов пищи в день: {meals}

Формат вывода (строго придерживайся):
День 1:
- Завтрак: название блюда
  Рецепт: пошаговое описание, используя только разрешённые продукты.
- Обед: ...
  Рецепт: ...
- Ужин: ...
  Рецепт: ...

День 2:
...

⚠️ Обязательные правила:
1. Используй только продукты из списка выше — никаких “новых” ингредиентов.
2. Если невозможно составить уникальные блюда на все дни, повторяй блюда из предыдущих дней.
3. Не добавляй комментарии, калорийность, советы, “Примечания”, “Замены” или любые пояснения.
4. Не используй слова “можно добавить”, “альтернатива”, “по желанию”.
5. Ответ должен содержать только дни, приёмы пищи и рецепты.
6. Каждый рецепт должен быть кратким и состоять из доступных продуктов.

Отвечай строго в заданном формате.
"""

    plan = ask_gigachat(prompt)

    # Простая защита от появления нежелательных разделов
    for banned_section in ["Примечания", "Советы", "Комментар", "Заключ", "Замена"]:
        if banned_section.lower() in plan.lower():
            plan = plan.split(banned_section)[0]

    return plan.strip()
