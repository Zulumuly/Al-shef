from logic.llm.gigachat_api import ask_gigachat

def generate_meal_plan(products: str, days: int, meals: int) -> str:
    prompt = f"""
Ты — нутрициолог и шеф-повар. На основе данных ниже создай сбалансированный план питания.

📦 Продукты: {products}
📅 Количество дней: {days}
🍽️ Количество приёмов пищи в день: {meals}

⚙️ Формат ответа:
- Чётко укажи день и приёмы пищи (завтрак, обед, ужин и т.п.)
- Под каждым блюдом — краткий рецепт (ингредиенты и способ приготовления)
- Без вступлений, без пояснений, без заключений
- Только план и рецепты
"""

    return ask_gigachat(prompt)
