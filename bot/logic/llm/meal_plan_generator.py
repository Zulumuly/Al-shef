from logic.llm.gigachat_api import ask_gigachat

def generate_meal_plan(products: str, days: int, meals_per_day: int) -> str:
    """
    Формирует жёсткий промт для GigaChat.
    """

    prompt = f"""
Ты — профессиональный диетолог и шеф-повар. 
Составь персональный план питания ровно на {days} {'день' if days == 1 else 'дней'}.

Правила:
1. Используй ТОЛЬКО продукты из списка пользователя — никаких других.
2. Составь ровно {meals_per_day} приём(а) пищи в день. Ни больше, ни меньше.
3. Каждый приём пищи — одно блюдо. Если приёмов меньше 3, не добавляй "перекусы".
4. Для каждого блюда укажи короткий рецепт (2–4 шага).
5. Не добавляй комментарии, советы, примечания и калорийность.
6. Формат вывода строго такой:

День 1:
- Приём 1: <название блюда>
  Рецепт: <пошагово>

Если дней больше одного — повтори структуру, но не меняй формат.

Доступные продукты:
{products}
"""

    return ask_gigachat(prompt)
